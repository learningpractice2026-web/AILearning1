"""Exports driven by usecase.yaml: Markdown, DOCX, PDF, Jira-importable CSV, email draft, JSON."""
from __future__ import annotations

import csv
import io

from core.schemas import Insights, Item
from core.usecase import Section, UseCase, get_usecase


def _line(it: Item, sec: Section) -> str:
    extra = [f"{sec.owner_label}: {it.owner}" if it.owner else "", f"Due: {it.deadline}" if it.deadline else "",
             *[f"{k}: {v}" for k, v in it.attributes.items() if v], "" if it.grounded else "NEEDS REVIEW"]
    extra = [e for e in extra if e]
    return it.text + (f" ({'; '.join(extra)})" if extra else "")


def _meta_line(date: str, ins: Insights, uc: UseCase) -> str:
    parts = [f"Date: {date or '-'}"] + [f"{f.label or f.name}: {ins.fields.get(f.name, '-')}" for f in uc.fields]
    return "  |  ".join(parts)


def to_markdown(title: str, date: str, ins: Insights, uc: UseCase | None = None) -> str:
    uc = uc or get_usecase()
    out = [f"# {title}", f"*{_meta_line(date, ins, uc)}*", "", "## Summary", ins.summary, ""]
    if ins.highlights:
        out += ["## Highlights", *[f"- {p}" for p in ins.highlights], ""]
    for sec in uc.sections:
        items = ins.sections.get(sec.key, [])
        out.append(f"## {sec.label}")
        if sec.is_task and items:
            attr_names = [a.name for a in sec.attributes]
            out += ["| # | Item | " + sec.owner_label + " | Deadline | " + "".join(f"{a} | " for a in attr_names) + "Status |",
                    "|---|---|---|---|" + "---|" * len(attr_names) + "---|"]
            out += [f"| {i} | {a.text} | {a.owner or 'Unassigned'} | {a.deadline or '-'} | "
                    + "".join(f"{a.attributes.get(n, '-')} | " for n in attr_names) + f"{a.status} |"
                    for i, a in enumerate(items, 1)]
        else:
            out += [f"- {_line(it, sec)}" for it in items] or ["- None recorded"]
        out.append("")
    out.append(f"_Generated by {uc.app.name}. Items marked NEEDS REVIEW were not verified against the source._")
    return "\n".join(out)


def to_docx(title: str, date: str, ins: Insights, uc: UseCase | None = None) -> bytes:
    from docx import Document
    uc = uc or get_usecase()
    d = Document()
    d.add_heading(title, 0)
    d.add_paragraph(_meta_line(date, ins, uc))
    d.add_heading("Summary", 1)
    d.add_paragraph(ins.summary)
    for sec in uc.sections:
        d.add_heading(sec.label, 1)
        items = ins.sections.get(sec.key, [])
        if sec.is_task and items:
            t = d.add_table(rows=1, cols=4)
            t.style = "Light Grid Accent 1"
            for c, h in zip(t.rows[0].cells, ["Item", sec.owner_label, "Deadline", "Status"]):
                c.text = h
            for a in items:
                r = t.add_row().cells
                r[0].text, r[1].text, r[2].text, r[3].text = a.text, a.owner or "Unassigned", a.deadline or "-", a.status
        else:
            for it in items:
                d.add_paragraph(_line(it, sec), style="List Bullet")
            if not items:
                d.add_paragraph("None recorded")
    buf = io.BytesIO()
    d.save(buf)
    return buf.getvalue()


def to_pdf(title: str, date: str, ins: Insights, uc: UseCase | None = None) -> bytes:
    from xml.sax.saxutils import escape

    from reportlab.lib.pagesizes import A4
    from reportlab.lib.styles import getSampleStyleSheet
    from reportlab.platypus import ListFlowable, ListItem, Paragraph, SimpleDocTemplate, Spacer
    uc = uc or get_usecase()
    st = getSampleStyleSheet()
    flow = [Paragraph(escape(title), st["Title"]), Paragraph(escape(_meta_line(date, ins, uc)), st["Normal"]),
            Spacer(1, 10), Paragraph("Summary", st["Heading2"]), Paragraph(escape(ins.summary), st["BodyText"])]
    for sec in uc.sections:
        flow.append(Paragraph(escape(sec.label), st["Heading2"]))
        items = ins.sections.get(sec.key, [])
        flow.append(ListFlowable([ListItem(Paragraph(escape(_line(i, sec)), st["BodyText"])) for i in items]
                                 or [ListItem(Paragraph("None recorded", st["BodyText"]))], bulletType="bullet"))
    buf = io.BytesIO()
    SimpleDocTemplate(buf, pagesize=A4, title=title).build(flow)
    return buf.getvalue()


def to_jira_csv(title: str, ins: Insights, uc: UseCase | None = None) -> bytes:
    """Jira 'External System Import' CSV. Task section -> Tasks; other sections -> labelled issues."""
    uc = uc or get_usecase()
    buf = io.StringIO()
    w = csv.writer(buf)
    w.writerow(["Summary", "Issue Type", "Assignee", "Due Date", "Description", "Labels"])
    for sec in uc.sections:
        for it in ins.sections.get(sec.key, []):
            prefix = "" if sec.is_task else f"[{sec.label}] "
            attrs = "; ".join(f"{k}={v}" for k, v in it.attributes.items())
            w.writerow([(prefix + it.text)[:250], "Task" if sec.is_task else "Story", it.owner or "",
                        it.deadline or "", f"Source: {title}\nEvidence: {it.evidence}\n{attrs}",
                        f"ai-generated,{sec.key}"])
    return buf.getvalue().encode("utf-8")


def to_email(title: str, date: str, ins: Insights, uc: UseCase | None = None) -> str:
    uc = uc or get_usecase()
    body = [f"Subject: {uc.app.record_name} summary - {title} ({date})", "", "Hi team,", "", ins.summary, ""]
    for sec in uc.sections:
        items = ins.sections.get(sec.key, [])
        if items:
            body.append(f"{sec.label}:")
            body += [f"  - {_line(it, sec)}" for it in items]
            body.append("")
    body += ["Please reply if anything is missing or wrong.", "", "Regards"]
    return "\n".join(body)
